using System;
using System.Buffers.Binary;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace League_Data_Recorder;

// Read only MP4 headers, seeking over compressed video. No decode, remux, FFmpeg,
// or change to the recording is involved. ScreenRecorderLib writes nonfragmented
// MP4s; unsupported timelines fail explicitly so the original audio is preserved.
internal sealed record Mp4VideoTimeline(
    double DurationSeconds, double FirstFrameEndSeconds, int SampleCount)
{
    private readonly record struct Box(string Type, long Start, long End);
    private readonly record struct Run(int Count, long Value);
    private const int MaximumSamples = 10_000_000;

    internal static Mp4VideoTimeline Read(string path)
    {
        using var input = new FileStream(path, FileMode.Open, FileAccess.Read,
            FileShare.Read | FileShare.Delete, 65536, FileOptions.RandomAccess);
        List<Box> top = Boxes(input, 0, input.Length);
        if (top.Any(b => b.Type == "moof"))
            throw new InvalidDataException("Fragmented MP4 timing is not supported for audio alignment.");
        Box movie = Require(top, "moov");
        List<Box> movieBoxes = Boxes(input, movie.Start, movie.End);
        uint movieScale = TimeScale(input, Require(movieBoxes, "mvhd"));

        foreach (Box track in movieBoxes.Where(b => b.Type == "trak"))
        {
            List<Box> trackBoxes = Boxes(input, track.Start, track.End);
            Box media = Require(trackBoxes, "mdia");
            List<Box> mediaBoxes = Boxes(input, media.Start, media.End);
            Box handler = Require(mediaBoxes, "hdlr");
            Need(handler, 12);
            input.Position = handler.Start + 8;
            if (FourCC(input) != "vide") continue;
            uint scale = TimeScale(input, Require(mediaBoxes, "mdhd"));
            Box info = Require(mediaBoxes, "minf");
            Box table = Require(Boxes(input, info.Start, info.End), "stbl");
            List<Box> tables = Boxes(input, table.Start, table.End);
            List<Run> durations = Runs(input, Require(tables, "stts"), signed: false);
            long count = durations.Sum(run => (long)run.Count);
            if (count <= 0 || count > MaximumSamples)
                throw new InvalidDataException("The MP4 has no usable video sample table.");

            Box? composition = Find(tables, "ctts");
            List<Run>? offsets = composition is Box ctts
                ? Runs(input, ctts, signed: Version(input, ctts) == 1) : null;
            if (offsets != null && offsets.Sum(run => (long)run.Count) != count)
                throw new InvalidDataException("The MP4 composition and duration tables disagree.");

            // A single, normal-rate media edit plus optional empty lead-in is the
            // layout generated by Media Foundation. Account for edit offsets and
            // B-frame composition offsets instead of assuming decode time = display time.
            double leadSeconds = 0;
            long mediaStart = 0;
            double? editDuration = null;
            if (Find(trackBoxes, "edts") is Box edits &&
                Find(Boxes(input, edits.Start, edits.End), "elst") is Box elst)
            {
                byte version = Version(input, elst);
                int entrySize = version == 1 ? 20 : 12;
                input.Position = elst.Start + 4;
                uint entries = U32(input);
                if (entries > (elst.End - input.Position) / entrySize)
                    throw new InvalidDataException("Invalid MP4 edit table.");
                bool mediaSeen = false;
                for (uint i = 0; i < entries; i++)
                {
                    ulong duration = version == 1 ? U64(input) : U32(input);
                    long start = version == 1 ? I64(input) : unchecked((int)U32(input));
                    uint rate = U32(input);
                    if (rate != 0x00010000 || mediaSeen)
                        throw new InvalidDataException("Only a single normal-speed MP4 media edit is supported.");
                    if (start == -1) leadSeconds += duration / (double)movieScale;
                    else if (start >= 0)
                    {
                        mediaStart = start;
                        // A zero-duration edit extends over all subsequent media.
                        editDuration = duration == 0 ? null : duration / (double)movieScale;
                        mediaSeen = true;
                    }
                    else throw new InvalidDataException("Invalid MP4 edit start.");
                }
                if (!mediaSeen) throw new InvalidDataException("The MP4 edit list contains no video.");
            }

            long decodeStart = 0;
            long capturedFirstPresentation = offsets is null ? 0 : offsets[0].Value;
            long capturedFirstEnd = checked(capturedFirstPresentation + durations[0].Value);
            long firstPresentation = long.MaxValue;
            long firstEnd = 0;
            long lastEnd = 0;
            int offsetRun = 0;
            int offsetRemaining = offsets is { Count: > 0 } ? offsets[0].Count : 0;
            foreach (Run duration in durations)
            {
                for (int n = 0; n < duration.Count; n++)
                {
                    long offset = offsets == null ? 0 : offsets[offsetRun].Value;
                    long presentation = checked(decodeStart + offset);
                    long end = checked(presentation + duration.Value);
                    if (end > mediaStart && presentation < firstPresentation)
                    {
                        firstPresentation = presentation;
                        firstEnd = end;
                    }
                    lastEnd = Math.Max(lastEnd, end);
                    decodeStart = checked(decodeStart + duration.Value);
                    if (offsets != null && --offsetRemaining == 0 && offsetRun + 1 < offsets.Count)
                        offsetRemaining = offsets[++offsetRun].Count;
                }
            }

            // Composition offsets can place the first frame AFTER mediaStart.
            // That is a valid presentation lead-in (e.g. an H.264 B-frame reorder
            // delay), not evidence that the first captured frame was removed.
            // Anchor to its actual presentation end, including that lead-in.
            // Still reject an edit that removes frame 1, or a layout where an
            // earlier picture has replaced it as the first displayed sample.
            if (firstPresentation == long.MaxValue || capturedFirstEnd <= mediaStart ||
                firstPresentation != capturedFirstPresentation)
                throw new InvalidDataException("The first captured video sample is not the first visible MP4 sample.");
            double firstFrameEnd = leadSeconds + (firstEnd - mediaStart) / (double)scale;
            double total = leadSeconds + (editDuration ?? (lastEnd - mediaStart) / (double)scale);
            if (!double.IsFinite(total) || total <= 0 || firstFrameEnd <= 0 || firstFrameEnd > total)
                throw new InvalidDataException("The MP4 presentation timing is invalid.");
            return new(total, firstFrameEnd, checked((int)count));
        }
        throw new InvalidDataException("The MP4 contains no video track.");
    }

    private static List<Box> Boxes(Stream input, long start, long end)
    {
        var boxes = new List<Box>();
        for (long position = start; position < end;)
        {
            if (end - position < 8) throw new InvalidDataException("Truncated MP4 box.");
            input.Position = position;
            ulong size = U32(input);
            string type = FourCC(input);
            int headerSize = 8;
            if (size == 1) { size = U64(input); headerSize = 16; }
            else if (size == 0) size = checked((ulong)(end - position));
            if (size < (ulong)headerSize || size > (ulong)(end - position))
                throw new InvalidDataException("Invalid MP4 box size.");
            long boxEnd = checked(position + (long)size);
            boxes.Add(new(type, position + headerSize, boxEnd));
            position = boxEnd;
        }
        return boxes;
    }

    private static List<Run> Runs(Stream input, Box box, bool signed)
    {
        Version(input, box);
        Need(box, 8);
        input.Position = box.Start + 4;
        uint count = U32(input);
        if (count > (box.End - input.Position) / 8 || count > MaximumSamples)
            throw new InvalidDataException("Invalid MP4 sample run table.");
        var runs = new List<Run>(checked((int)count));
        for (uint i = 0; i < count; i++)
        {
            uint samples = U32(input);
            uint value = U32(input);
            if (samples == 0 || samples > MaximumSamples)
                throw new InvalidDataException("Invalid MP4 sample run length.");
            runs.Add(new((int)samples, signed ? unchecked((int)value) : (long)value));
        }
        return runs;
    }

    private static uint TimeScale(Stream input, Box box)
    {
        byte version = Version(input, box);
        int offset = version == 1 ? 20 : 12;
        Need(box, offset + 4);
        input.Position = box.Start + offset;
        uint value = U32(input);
        if (value == 0) throw new InvalidDataException("The MP4 timescale is zero.");
        return value;
    }

    private static byte Version(Stream input, Box box)
    {
        Need(box, 4);
        input.Position = box.Start;
        int version = input.ReadByte();
        if (version is not (0 or 1)) throw new InvalidDataException("Unsupported MP4 box version.");
        return (byte)version;
    }

    private static void Need(Box box, int bytes)
    {
        if (box.End - box.Start < bytes) throw new InvalidDataException("Truncated MP4 timing table.");
    }
    private static Box? Find(List<Box> boxes, string type)
    {
        foreach (Box box in boxes) if (box.Type == type) return box;
        return null;
    }
    private static Box Require(List<Box> boxes, string type) => Find(boxes, type)
        ?? throw new InvalidDataException("Missing MP4 " + type + " box.");
    private static string FourCC(Stream input)
    {
        Span<byte> data = stackalloc byte[4];
        input.ReadExactly(data);
        return Encoding.ASCII.GetString(data);
    }
    private static uint U32(Stream input)
    {
        Span<byte> data = stackalloc byte[4];
        input.ReadExactly(data);
        return BinaryPrimitives.ReadUInt32BigEndian(data);
    }
    private static ulong U64(Stream input)
    {
        Span<byte> data = stackalloc byte[8];
        input.ReadExactly(data);
        return BinaryPrimitives.ReadUInt64BigEndian(data);
    }
    private static long I64(Stream input) => unchecked((long)U64(input));
}
